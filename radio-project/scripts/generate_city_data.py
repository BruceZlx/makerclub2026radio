#!/usr/bin/env python3
"""Generate the shared C++ city table from the single JSON edit source."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from radio_config import config_id, load_and_validate  # noqa: E402


def cxx_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def cxx_number(value: float) -> int:
    return int(round(float(value) * 1000.0))


def render(config: dict) -> str:
    origin = config["origin"]
    lines = [
        "#pragma once",
        "",
        '#include "city_catalog.h"',
        "",
        "namespace radio {",
        "namespace generated {",
        "",
        "// Generated by scripts/generate_city_data.py. Do not edit by hand.",
        f"// config_id = {config_id(config)}",
        "",
    ]
    cities = config.get("cities", [])
    if cities:
        lines.append("inline constexpr City kCities[] = {")
        for city in cities:
            lines.append("    City{")
            lines.append(f"        {city['id']},")
            lines.append(f"        {cxx_string(city['code'])},")
            lines.append(f"        {cxx_string(city['name'])},")
            lines.append(f"        {cxx_number(city['longitude'])},")
            lines.append(f"        {cxx_number(city['latitude'])},")
            lines.append(f"        {cxx_string(city['primaryUrl'])},")
            lines.append(f"        {cxx_string(city['backupUrl'])},")
            lines.append(f"        {cxx_string(city['primaryStation'])},")
            lines.append(f"        {cxx_string(city['backupStation'])},")
            lines.append(f"        {cxx_string(city['offlinePath'])},")
            lines.append(f"        {cxx_string(city['offlineLabel'])},")
            lines.append(f"        {cxx_string(city['timezoneRule'])},")
            lines.append(f"        {cxx_string(city['copy'])},")
            lines.append(f"        {city['displayOrder']},")
            lines.append("    },")
        lines.append("};")
    else:
        lines.append("inline constexpr City kCities[1] = {City{}};")
    lines.extend(
        [
            f"inline constexpr size_t kCityCount = {len(cities)};",
            "inline constexpr GeoPoint kOrigin{"
            f"{cxx_number(origin['longitude'])}, {cxx_number(origin['latitude'])}}};",
            f'inline constexpr char kConfigId[] = "{config_id(config)}";',
            f"inline constexpr bool kComplete = {'true' if config.get('complete') else 'false'};",
            "",
            "}  // namespace generated",
            "}  // namespace radio",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--input", default="config/cities.json")
    parser.add_argument("--output", default="firmware/shared/generated/city_data.h")
    parser.add_argument("--allow-incomplete", action="store_true")
    parser.add_argument("--print-config-id", action="store_true")
    args = parser.parse_args()

    try:
        config, errors = load_and_validate(args.input, require_complete=False)
    except Exception as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1
    if errors:
        for error in errors:
            print(f"ERROR: {error}", file=sys.stderr)
        return 1
    if not config.get("complete") and not args.allow_incomplete:
        print(
            "ERROR: 正式 cities.json 不完整，拒绝生成固件城市表；"
            "补齐8城真实数据后重试。",
            file=sys.stderr,
        )
        return 2

    header = render(config)
    output = Path(args.output)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(header, encoding="utf-8")
    if args.print_config_id:
        print(config_id(config))
    print(f"generated {output} ({len(config.get('cities', []))} cities)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
